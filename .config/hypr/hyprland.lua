hl.config({ autogenerated = false })

hl.on("hyprland.start", function()
    hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP DISPLAY XDG_RUNTIME_DIR DBUS_SESSION_BUS_ADDRESS")
    hl.exec_cmd("systemctl --user import-environment WAYLAND_DISPLAY XDG_CURRENT_DESKTOP DISPLAY")

    hl.exec_cmd("uwsm-app noctalia")
    hl.exec_cmd("uwsm-app -- foot --server")
    hl.exec_cmd("uwsm-app -- thunar --daemon")
end)

